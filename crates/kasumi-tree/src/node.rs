/// What a node represents. This affects layout participation, painting,
/// hit-testing and the accessibility tree.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum NodeKind {
    Root,
    Container,
    /// A container whose children share one grid cell.
    Stack,
    /// An absolutely positioned root-level layer, painted after page content.
    Overlay,
    Text,
    Button,
    TextInput,
    Spacer,
    Image,
    Checkbox,
    Radio,
    Slider,
    ProgressBar,
    ComboBox,
    /// A floating menu panel.
    Menu,
    /// One selectable row inside a menu panel.
    MenuItem,
    /// A navigation drawer panel.
    NavigationDrawer,
    /// One row of a navigation drawer or rail.
    NavigationItem,
    /// A text field combined with a results popup.
    SearchField,
    /// A multi-line code/text editor with a gutter and syntax highlighting.
    TextEditor,
    /// A Material 3 switch.
    Switch,
}

/// Which interactions a node participates in.
#[derive(Debug, Default, Clone, Copy, PartialEq, Eq)]
pub struct Sense(u8);

impl Sense {
    pub const NONE: Sense = Sense(0);
    pub const HOVER: Sense = Sense(1 << 0);
    pub const CLICK: Sense = Sense(1 << 1);
    pub const FOCUS: Sense = Sense(1 << 2);
    pub const DRAG: Sense = Sense(1 << 3);

    pub const fn hover() -> Self {
        Self(Self::HOVER.0)
    }

    pub const fn click() -> Self {
        Self(Self::HOVER.0 | Self::CLICK.0 | Self::FOCUS.0)
    }

    pub const fn focusable() -> Self {
        Self(Self::FOCUS.0)
    }

    pub const fn union(self, other: Self) -> Self {
        Self(self.0 | other.0)
    }

    pub const fn contains(self, other: Self) -> bool {
        self.0 & other.0 == other.0
    }

    pub const fn is_hoverable(self) -> bool {
        self.0 & Self::HOVER.0 != 0
    }

    pub const fn is_clickable(self) -> bool {
        self.0 & Self::CLICK.0 != 0
    }

    pub const fn is_focusable(self) -> bool {
        self.0 & Self::FOCUS.0 != 0
    }

    pub const fn is_draggable(self) -> bool {
        self.0 & Self::DRAG.0 != 0
    }
}

/// A single edit delivered to a text input by the runtime.
#[derive(Debug, Clone, PartialEq)]
pub enum TextEdit {
    Insert(String),
    Backspace,
    BackspaceWord,
    Delete,
    DeleteWord,
    MoveCaret {
        motion: TextMotion,
        extend: bool,
        by_word: bool,
    },
    SelectAll,
    /// Programmatically place the caret and selection, in byte offsets.
    ///
    /// Applications use this for go-to-definition, search results and
    /// completion acceptance. The widget clamps the offsets to the current
    /// text and keeps the caret visible.
    SetSelection {
        anchor: usize,
        cursor: usize,
    },
    /// A multi-line editor: pointer position, selection and click count.
    PointerDown {
        x: f32,
        y: f32,
        extend: bool,
    },
    PointerDrag {
        x: f32,
        y: f32,
    },
    PointerUp,
    SelectWord {
        x: f32,
        y: f32,
    },
    /// Select the whole logical line under the pointer (triple click).
    SelectLine {
        y: f32,
    },
    Paste(String),
    Copy,
    Cut,
    Undo,
    Redo,
    SetPreedit {
        text: String,
        cursor: Option<(usize, usize)>,
    },
    /// Insert a newline, carrying the current line's indentation.
    NewLine,
    /// Indent or outdent the selection (or the current line) by one level.
    Indent {
        outdent: bool,
    },
    /// Move whole selected lines up or down.
    MoveLines {
        up: bool,
    },
    /// Duplicate the selection or the current line.
    DuplicateLine,
    /// Toggle `//` line comments on the selected lines.
    ToggleComment,
    /// Delete the current logical line.
    DeleteLine,
    /// Insert the matching closing bracket / quote pair, or skip over an
    /// auto-inserted one.
    InsertPair {
        opening: char,
    },
}

/// Logical caret movement generated by keyboard input.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TextMotion {
    Left,
    Right,
    Home,
    End,
    /// Up/down by visual lines, keeping a sticky horizontal goal column.
    Up,
    Down,
    /// Ctrl+Home / Ctrl+End: start or end of the document.
    DocumentStart,
    DocumentEnd,
    /// PageUp / PageDown by a viewport worth of lines.
    PageUp,
    PageDown,
    /// Jump to a matching bracket of the one next to the caret.
    MatchingBracket,
}

/// One undo/redo checkpoint. Text is stored alongside selection because an
/// edit may replace either a single grapheme or a large selection.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TextEditSnapshot {
    pub text: String,
    pub anchor: usize,
    pub cursor: usize,
}

/// Per-node text-input buffer. Widgets drain `pending` during `view`.
#[derive(Debug, Default, Clone, PartialEq)]
pub struct TextInputState {
    pub pending: Vec<TextEdit>,
    /// Selection endpoint that stays put while the caret moves.
    pub anchor: usize,
    /// Active selection/caret endpoint, in UTF-8 byte offsets.
    pub cursor: usize,
    /// Caret and selection offsets in the painted string. These differ from
    /// `cursor`/`anchor` while an IME pre-edit is visible.
    pub paint_anchor: usize,
    pub paint_cursor: usize,
    pub scroll_x: f32,
    /// Vertical scroll offset for multi-line editors, in logical pixels.
    pub scroll_y: f32,
    /// Sticky horizontal goal column used by Up/Down motion.
    pub goal_column: f32,
    /// Text last rendered into this editor. Used to detect external State
    /// writes without storing a duplicate authoritative copy across frames.
    pub last_value: Option<String>,
    pub undo: Vec<TextEditSnapshot>,
    pub redo: Vec<TextEditSnapshot>,
    pub preedit: String,
    pub preedit_cursor: Option<(usize, usize)>,
}

/// Retained scrolling and animation state for a scroll view.
#[derive(Debug, Default, Clone, Copy, PartialEq)]
pub struct ScrollState {
    pub offset: Point,
    pub target: Point,
    pub velocity: Point,
    /// Chromium-style wheel animation. Owns the authoritative animated
    /// position and pending destination.
    pub physics: ScrollPhysics,
    /// Natural content extent in the container's unshifted coordinate space.
    pub content_size: Size,
    /// False for reduced-motion or explicitly instant scrolling.
    pub smooth: bool,
}

impl ScrollState {
    pub fn is_animating(&self) -> bool {
        self.physics.is_animating()
    }

    pub fn scroll_range(&self, viewport: Size) -> Point {
        Point::new(
            (self.content_size.width - viewport.width).max(0.0),
            (self.content_size.height - viewport.height).max(0.0),
        )
    }

    /// Clamps both the rendered offset and the pending destination to the
    /// current scroll range.
    pub fn clamp_to(&mut self, viewport: Size) {
        let range = self.scroll_range(viewport);
        let offset = Point::new(
            self.offset.x.clamp(0.0, range.x),
            self.offset.y.clamp(0.0, range.y),
        );
        self.offset = offset;
        self.target.x = self.target.x.clamp(0.0, range.x);
        self.target.y = self.target.y.clamp(0.0, range.y);

        // An idle animation must agree with the clamped offset. A running one
        // is re-targeted by `advance` on the next tick instead.
        if !self.physics.is_animating() && self.physics.position() != offset {
            self.physics.reset(offset);
        }
    }

    /// Places the offset at `position` immediately, cancelling any animation.
    pub fn jump_to(&mut self, position: Point) {
        self.offset = position;
        self.target = position;
        self.velocity = Point::ZERO;
        self.physics.reset(position);
    }

    /// Moves the retained target to `destination`.
    ///
    /// `smooth` is the request's preference; the scroll view's own `smooth`
    /// setting still wins.
    pub fn scroll_to(&mut self, now: f64, destination: Point, smooth: bool) {
        self.target = destination;

        if !smooth || !self.smooth {
            self.jump_to(destination);
            return;
        }

        self.physics.scroll_to(now, destination);
        self.offset = self.physics.position();
        self.target = self.physics.target();
        self.velocity = self.physics.velocity(now);
    }

    /// Advances the animation to `now`, re-clamping it against `viewport`.
    ///
    /// Returns `true` while another frame is needed.
    pub fn advance(&mut self, now: f64, viewport: Size) -> bool {
        self.clamp_to(viewport);

        if !self.smooth {
            let target = self.target;
            self.jump_to(target);
            return false;
        }

        // Layout or a content resize may have clamped the destination while a
        // segment was in flight. Re-target from the current position and
        // velocity rather than jumping to the new destination.
        if self.physics.is_animating() && self.physics.target() != self.target {
            self.physics.retarget(now, self.target);
        }

        let mut animating = self.physics.step(now);
        let range = self.scroll_range(viewport);
        let position = Point::new(
            self.physics.position().x.clamp(0.0, range.x),
            self.physics.position().y.clamp(0.0, range.y),
        );

        if position != self.physics.position() {
            self.physics.reset(position);
            self.target = position;
            animating = false;
        }

        self.offset = self.physics.position();
        self.target = self.physics.target();
        self.velocity = if animating {
            self.physics.velocity(now)
        } else {
            Point::ZERO
        };

        animating
    }
}

pub type Animation = Animated;

/// One retained element.
pub struct Node {
    pub id: Id,
    pub kind: NodeKind,
    /// Whether interactive widgets accept input. This is retained separately
    /// from `sense` because disabled widgets may still hold focus.
    pub enabled: bool,
    pub parent: Option<NodeId>,
    /// Children from the previous committed frame, in paint order.
    pub children: Vec<NodeId>,
    /// Children declared during the current frame.
    pub scratch_children: Vec<NodeId>,
    pub scratch_frame: u64,
    pub style: Style,
    pub text: Option<TextContent>,
    pub text_input: Option<TextInputState>,
    pub image: Option<Arc<ImageData>>,
    pub image_fit: ImageFit,
    /// Checked state for checkboxes and radios.
    pub checked: bool,
    /// Value and range for sliders.
    pub slider_value: f32,
    pub slider_min: f32,
    pub slider_max: f32,
    /// Open state for combo boxes and other retained popups.
    pub popup_open: bool,
    /// Optional accessible name when the visible descendants are icons or
    /// otherwise unsuitable as a label.
    pub accessibility_label: Option<String>,
    /// Excludes this node and its descendants from the accessibility snapshot.
    pub a11y_hidden: bool,
    /// Width used by the last layout measurement for this text node. Paint
    /// shapes at the same width so it does not disagree with the height the
    /// layout pass reserved.
    pub text_shape_width: Cell<Option<f32>>,
    /// Absolute bounds from the previous layout pass.
    pub rect: Rect,
    pub sense: Sense,
    pub last_seen: u64,
    pub style_dirty: bool,
    pub children_dirty: bool,
    pub content_dirty: bool,
    pub layout_dirty: bool,
    pub animations: HashMap<Box<str>, Animated>,
    pub visual: AnimationState,
    /// Set by widgets such as text inputs when the value was edited this frame.
    pub changed: bool,
    /// Continuous 0..=1 hover amount used by controls with soft transitions.
    pub hover_progress: f32,
    /// Retained offset, target and velocity for scroll containers.
    pub scroll: ScrollState,
    /// Widget-declared content extent. When set, `update_scroll_metrics` uses
    /// it instead of measuring children, which lets virtualized widgets and
    /// code editors publish a content size they never declare as nodes.
    pub scroll_content_override: Option<Size>,
    /// Whether this scroll container paints its own scrollbar rail/thumb.
    pub show_scrollbars: bool,
    /// Paint data for a Material 3 switch, filled by the widget each frame.
    pub switch: Option<crate::switch_paint::SwitchPaint>,
    /// Paint data for a multi-line editor, filled by the widget each frame.
    pub editor: Option<EditorPaint>,
}

impl Node {
    pub fn new(id: Id, kind: NodeKind) -> Self {
        Self {
            id,
            kind,
            enabled: true,
            parent: None,
            children: Vec::new(),
            scratch_children: Vec::new(),
            scratch_frame: 0,
            style: Style::default(),
            text: None,
            text_input: None,
            image: None,
            image_fit: ImageFit::Contain,
            checked: false,
            slider_value: 0.0,
            slider_min: 0.0,
            slider_max: 1.0,
            popup_open: false,
            accessibility_label: None,
            a11y_hidden: false,
            text_shape_width: Cell::new(None),
            rect: Rect::ZERO,
            sense: Sense::NONE,
            last_seen: 0,
            style_dirty: true,
            children_dirty: true,
            content_dirty: true,
            layout_dirty: true,
            animations: HashMap::new(),
            visual: AnimationState::default(),
            changed: false,
            hover_progress: 0.0,
            scroll: ScrollState::default(),
            scroll_content_override: None,
            show_scrollbars: true,
            switch: None,
            editor: None,
        }
    }

    pub fn is_layout_dirty(&self) -> bool {
        self.style_dirty || self.children_dirty || self.content_dirty || self.layout_dirty
    }

    pub fn text_str(&self) -> Option<&str> {
        self.text.as_ref().map(|text| text.text.as_str())
    }

    /// Advances every keyed channel and the visual transform for this node.
    pub fn tick_animations(&mut self, now: f64) -> bool {
        let mut running = false;
        for animation in self.animations.values_mut() {
            animation.sample(now);
            running |= animation.is_running(now);
        }
        running |= self.visual.any_running(now);
        running
    }

    pub fn animate_channel(
        &mut self,
        key: &str,
        target: f32,
        spec: MotionSpec,
        now: f64,
    ) -> (f32, bool) {
        let animation = self.animations.entry(key.into()).or_insert_with(|| {
            let mut animation = Animated::new(target);
            animation.start_from_zero();
            animation.snap(0.0);
            animation
        });
        animation.set_target(target, spec, now);
        let value = animation.sample(now);
        (value, animation.is_running(now))
    }
}
